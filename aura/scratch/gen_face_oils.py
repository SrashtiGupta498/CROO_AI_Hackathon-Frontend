def bullets(items):
    return "\n".join("• " + x for x in items)

def build(o):
    slug = o["title"].lower().replace(" ", "-")
    secs = [
        ("hero", o["title"], ""),
        ("text", "About", o["about"]),
        ("text", "Skin Benefits", bullets(o["skin"])),
        ("text", "Hair Benefits", bullets(o["hair"])),
        ("text", "Body Benefits", bullets(o["body"])),
        ("text", "Pros", bullets(o["pros"])),
        ("text", "Cons", bullets(o["cons"])),
        ("text", "How to Apply", o["apply"]),
        ("text", "Best Skin Types", o["best"]),
        ("text", "Comedogenic Rating", o["comedo"]),
        ("faq", "FAQ", o["faq"]),
        ("source", "Source", SOURCE),
    ]
    sections = []
    for i, (stype, title, body) in enumerate(secs):
        sec = {"type": stype, "title": title, "order": i}
        if stype == "hero":
            sec["subtitle"] = "Ingredient Reference"
        sec["body"] = body
        # match existing key order: type, title, subtitle?, body, order
        sec = {k: sec[k] for k in (["type", "title"] + (["subtitle"] if "subtitle" in sec else []) + ["body", "order"])}
        sections.append(sec)
    return {
        "_id": {"$oid": oid(slug)},
        "schemaVersion": 1,
        "type": "FACE_OIL",
        "authorId": AUTHOR,
        "title": o["title"],
        "slug": slug,
        "subtitle": "Ingredient Reference",
        "sections": sections,
        "thumbnailUrl": "",
        "palette": [],
        "tags": o["tags"],
        "ai": {"summary": o["summary"], "keywords": o["keywords"], "hashtags": o["hashtags"]},
        "seo": {
            "title": f"{o['title']} | Organic Oils Ingredient Reference",
            "description": o["summary"][:155],
            "slug": slug,
        },
        "isPublished": True,
        "visibility": "public",
        "contentLanguage": "en",
        "stats": {"views": 0, "likes": 0, "claps": 0, "bookmarks": 0, "comments": 0},
    }

docs = [build(o) for o in OILS]
